"""The policy fragment model.

A fragment is a *partial* policy — one layer of ``defaults → roles →
overlay``. Its shape is the one in ``contracts/schemas/baseline.schema.json``:
**flat**, every field optional, ``null`` meaning "inherit from the layer below".

    {"tools": [...], "files_read": [...], "files_write": [...],
     "network": "any", "auto_accept": "safe", "max_iterations": 40}

v1's fragment was nested (`capabilities.tools`, `files.read`, `budget.*`) and
every fragment could subtract. Two deliberate changes (gotchas N2):

* **Flat, because the contract is flat.** The baseline is generated by the Nix
  module and is what two parts agree on; the in-memory model follows it rather
  than translating at the boundary.
* **Only the overlay may take away.** List fields in a *baseline* fragment are
  plain lists that union, so a reader of the Nix configuration sees the whole
  grant by reading it forward. A list in the runtime overlay *replaces* what the
  layers below it gave, because an account's override is the final say on that
  field (D87). The shape is the same list either way; the layer decides.

``auto_accept``, ``max_iterations``, ``models`` and ``tokens_daily`` are declared
fields of the baseline schema as well as the overlay: approval mode and budgets
are policy an operator states in git, not runtime tuning. They were briefly
absent from the schema while this parser accepted them, which made a baseline
that set any of them fail validation at startup — the fields and the contract
are now checked against each other by fixture.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

__all__ = [
    "AUTO_ACCEPT_MODES",
    "LIST_FIELDS",
    "NETWORK_MODES",
    "SCALAR_DEFAULTS",
    "SCALAR_FIELDS",
    "FragmentError",
    "PolicyFragment",
]

LIST_FIELDS = ("tools", "files_read", "files_write", "models")

SCALAR_FIELDS = (
    # Whether tools declaring `needs = ["network"]` are offered at all. There is
    # no host list: those tools run on the acting user's own machine, so Neuman
    # cannot narrow where they connect (N146).
    "network",
    "auto_accept",
    # The most permissive approval mode this account may choose for itself.
    #
    # `auto_accept` is what is in force; this is the ceiling on it. Separating
    # the two is what lets the choice be a *user* setting without becoming a
    # self-granted one: an operator states how far a user may go, and the user
    # moves within it. A role capped at "safe" can stop approving every `ls` and
    # still cannot authorise its own destructive work.
    "auto_accept_max",
    "max_iterations",
    "tokens_daily",
)

# Ordered least to most permissive. The order is the whole point: it is what
# lets a ceiling be compared against a choice, so a user may move within what an
# operator granted and no further.
AUTO_ACCEPT_MODES = ("never", "safe", "yolo")


def auto_accept_rank(mode: str) -> int:
    """How permissive a mode is, as an index into `AUTO_ACCEPT_MODES`.

    Unknown modes rank as the strictest rather than raising: this is called on
    the enforcement path, and a mode that somehow escaped validation must fail
    closed rather than fail open.
    """

    try:
        return AUTO_ACCEPT_MODES.index(mode)
    except ValueError:
        return 0


# What `network` may be set to. Two values and no host list: the tools that need
# the network run on the acting user's own machine, so the grant decides whether
# they are offered, not where they may connect (N146).
NETWORK_MODES = ("none", "any")

# What an appliance does when no layer says otherwise. Deliberately the
# restrictive end of every axis: a fragment that forgets a field must not widen
# anything (docs/security-model.md — every failure path fails closed).
SCALAR_DEFAULTS: dict[str, Any] = {
    "network": "none",
    "auto_accept": "safe",
    # The *ceiling*, which defaults permissive — and that is deliberate, against
    # the usual rule that every default here is the restrictive end.
    #
    # What is restrictive is `auto_accept` itself: "safe" by default, so an
    # appliance that says nothing still asks before anything mutating. This field
    # only bounds how far a *user* may move that choice, so defaulting it to
    # "safe" would silently downgrade an operator who wrote
    # `auto_accept = "yolo"` in git and never heard of the ceiling — turning a
    # new field into a behaviour change for existing configurations. Caught by
    # `test_yolo_still_stops_at_anything_critical`, which asserts exactly
    # that an explicit "yolo" is honoured.
    #
    # So: the mode in force stays conservative, and an operator who wants to
    # *limit* a user states the limit. Nothing is widened by this default, since
    # a ceiling grants nothing on its own.
    "auto_accept_max": "yolo",
    # A runaway guard, not a work limit — which is what 20 had become.
    #
    # It was the restrictive end of the axis on the principle that every default
    # here should be, and that principle is about *reach*: a forgotten field
    # must not widen what an account may touch. Steps are not reach. A low value
    # does not make the appliance safer, it makes legitimate work fail — a
    # research turn hit 20 while debugging a parser and ended mid-thought (N87).
    #
    # 500 is chosen to be a number nobody reaches on purpose. The things that
    # actually bound a turn are `tokens_daily`, which meters spending, and the
    # human who can interrupt; this exists so that a model stuck in a retry loop
    # stops eventually rather than never. `pi` has no step limit at all
    # (`agent-loop.ts` is `while (true)`), which is defensible for a local CLI
    # with a watching human and not for an appliance serving accounts.
    #
    # The handoff note fires three steps from the end whatever this is set to,
    # so reaching it produces a summary rather than a severed turn.
    "max_iterations": 500,
    "tokens_daily": None,
}


class FragmentError(ValueError):
    """A fragment is not well-formed."""


def _strings(value: Any) -> list[str]:
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise FragmentError(f"expected a list of strings, got {value!r}")
    return value


@dataclass(frozen=True, slots=True)
class PolicyFragment:
    """One layer of policy. Absent fields inherit; they do not reset."""

    lists: dict[str, tuple[str, ...]] = field(default_factory=dict)
    scalars: dict[str, Any] = field(default_factory=dict)
    # A baseline list adds to the layers below; an overlay list replaces them.
    replaces: bool = False

    @classmethod
    def parse(cls, data: Any, *, replaces: bool = False) -> PolicyFragment:
        """Build a fragment from decoded JSON.

        ``replaces`` is True for the runtime overlay and nothing else.
        """

        if data is None:
            return cls()
        if not isinstance(data, dict):
            raise FragmentError(f"fragment must be an object, got {type(data).__name__}")

        known = set(LIST_FIELDS) | set(SCALAR_FIELDS)
        unknown = set(data) - known
        if unknown:
            raise FragmentError(f"unknown policy fields: {sorted(unknown)}")

        lists: dict[str, tuple[str, ...]] = {}
        for name in LIST_FIELDS:
            if data.get(name) is not None:
                lists[name] = tuple(_strings(data[name]))

        scalars: dict[str, Any] = {}
        for name in SCALAR_FIELDS:
            # A present-but-null scalar means inherit, which is the same as
            # absent; only a set value overrides.
            if name in data and data[name] is not None:
                scalars[name] = _check_scalar(name, data[name])

        return cls(lists=lists, scalars=scalars, replaces=replaces)

    def to_json(self) -> dict[str, Any]:
        """Serialize back to the wire shape (for export and the admin API)."""

        data: dict[str, Any] = {name: list(items) for name, items in self.lists.items()}
        data.update(self.scalars)
        return data


def _check_scalar(name: str, value: Any) -> Any:
    """Validate a scalar leaf. Shape only — reach is decided elsewhere."""

    if name in ("pids_max", "max_iterations", "tokens_daily"):
        if not isinstance(value, int) or isinstance(value, bool) or value < 1:
            raise FragmentError(f"{name} must be a positive integer, got {value!r}")
        return value
    if name == "network":
        if value not in NETWORK_MODES:
            raise FragmentError(f"network must be one of {NETWORK_MODES}, got {value!r}")
        return value
    if name in ("auto_accept", "auto_accept_max"):
        if value not in AUTO_ACCEPT_MODES:
            raise FragmentError(f"{name} must be one of {AUTO_ACCEPT_MODES}, got {value!r}")
        return value
    raise FragmentError(
        f"unhandled scalar {name}"
    )  # pragma: no cover - guarded by SCALAR_FIELDS
